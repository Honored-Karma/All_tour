import type { DestinationId, LocalizedText } from "./destinations";

export type TourType =
  | "content_tour"
  | "mountain_nature"
  | "cultural_city"
  | "multi_day";

export interface TourMedia {
  src: string;
  alt: LocalizedText;
  type: "photo" | "poster";
  sourceAsset?: string;
  caption?: LocalizedText;
}

export interface TourItineraryStep {
  title: LocalizedText;
  description: LocalizedText;
  time?: string;
  image?: string;
  optional?: boolean;
}

export interface Tour {
  id: string;
  slug: string;
  destinationId: DestinationId;
  tourType: TourType;
  title: LocalizedText;
  subtitle: LocalizedText;
  summary: LocalizedText;
  description: LocalizedText;
  /**
   * Optional confirmed duration. When undefined, UI displays "По запросу / На выбор".
   */
  duration?: LocalizedText;
  /** Confirmed route length used by duration filters; absent when unknown. */
  durationDays?: number;
  /**
   * Optional confirmed live price in KZT. Kept undefined until verified by owner.
   */
  priceKzt?: number;
  /**
   * Historical reference price printed on official promo posters (25 000 ₸, 85 000 ₸, 145 000 ₸).
   * Always displayed with a clear note that current pricing is confirmed on request.
   */
  posterReferencePriceKzt?: number;
  /**
   * Historical strike-through price printed on promo poster (e.g. 99 000 ₸ on photo_12).
   */
  posterOriginalPriceKzt?: number;
  priceVerified: boolean;
  /**
   * Historical promo dates printed on poster (never shown as guaranteed future dates).
   */
  posterReferenceDates?: LocalizedText;
  /**
   * Confirmed future departure dates. When empty, UI displays "Ближайшие даты — по запросу".
   */
  departureDates: string[];
  departureCity: LocalizedText;
  image: string;
  catalogCardImage?: string;
  catalogCardImagePosition?: string;
  gallery: string[];
  media: TourMedia[];
  sourceAssets: string[];
  itinerary: TourItineraryStep[];
  included: {
    ru: string[];
    kz: string[];
  };
  excluded: {
    ru: string[];
    kz: string[];
  };
  optionalActivities?: {
    ru: string[];
    kz: string[];
  };
  notes: {
    ru: string[];
    kz: string[];
  };
  documentsInfo: LocalizedText;
  status: "available" | "on_request" | "sold_out";
  featured: boolean;
}

